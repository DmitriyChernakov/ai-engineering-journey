import ollama

QUESTION = "Стоит ли мне учить Rust в 2026 году, если я уже знаю Python и работаю в QA?"

# 3 радикально разные роли
roles = {
    "Прагматичный ментор": """Ты — прагматичный технический ментор с 15-летним опытом.
Ты ценишь время ученика и никогда не рекомендуешь учить что-то «на всякий случай».
Отвечай конкретно: да/нет + обоснование в 3 пунктах. Без воды.""",

    "Восторженный евангелист": """Ты — евангелист языка Rust. Ты считаешь, что Rust —
лучший язык для всего, и будущее только за ним. Отвечай с энтузиазмом, 
приводи примеры успешных проектов, используй эмодзи.""",

    "Скептик-реалист": """Ты — скептичный инженер, который видел много хайпа за 20 лет.
Ты всегда указываешь на недостатки, скрытые издержки и кривую обучения. 
Отвечай честно и немного цинично, даже если это неприятно."""
}


def ask_role(role: str, sys_prompt: str, question: str):
    print(f"\n{'=' * 60}")
    print(f"Роль: {role}")
    print('=' * 60)
    response = ollama.chat(
        model='qwen2.5:7b',
        messages=[
            {'role': 'system', 'content': sys_prompt},
            {'role': 'user', 'content': question}
        ]
    )
    print(response.message.content)


if __name__ == '__main__':
    # Шаг 1: Прогоняем вопрос через 3 роли
    for role_name, system_prompt in roles.items():
        ask_role(role_name, system_prompt, QUESTION)

    # Шаг 2: Пишем свой промпт для QA Buddy
    print("\n" + "=" * 60)
    print("МОЙ QA SYSTEM PROMPT")
    print("=" * 60)

    QA_SYSTEM = """Ты — опытный WEB QA-инженер с 10-летним опытом в автоматизации (Python, Playwright).
    Твоя специализация: генерация тест-кейсов и анализ требований.
    Правила работы:
    1. Отвечай структурированно, используй markdown.
    2. Всегда думай о негативных сценариях и граничных случаях (edge cases).
    3. Если требование неполное — укажи, какие вопросы нужно задать бизнесу.
    4. Используй только функционал, который указан в описании."""

    feature = "Форма логина: поля email и пароль, кнопка 'Войти', ссылка 'Забыли пароль?'."

    response = ollama.chat(
        model='qwen2.5:7b',
        messages=[
            {'role': 'system', 'content': QA_SYSTEM},
            {'role': 'user', 'content': f'Проанализируй требование и предложи 5 тест-кейсов для фичи: {feature}'}
        ]
    )
    print(response.message.content)
